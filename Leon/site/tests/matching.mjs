import assert from 'node:assert/strict';
import { roster } from '../lib/roster.ts';
const base = process.argv[2] || 'http://127.0.0.1:5173';
assert(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Tests are local-only');
const users = [];
async function user(member) {
  const init = await fetch(`${base}/api/match`);
  assert.equal(init.status, 200, await init.clone().text());
  const cookie = init.headers.get('set-cookie')?.split(';')[0];
  assert(cookie);
  const u = { member, async call(body) {
    const r = await fetch(`${base}/api/match`, { method: body ? 'POST' : 'GET', headers: { cookie, origin: new URL(base).origin, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: r.status, ...await r.json() };
  }, async join() { return this.call({ action: 'join', memberId: member.id, team: member.team }); } };
  users.push(u); return u;
}
const ai = roster.filter(m => m.department === 'AI');
const full = roster.filter(m => m.department === '풀스택');
const cloud = roster.filter(m => m.department === '클라우드');
try {
  const a = await user(ai[0]), b = await user(full[0]), c = await user(ai[1]);
  const baseline = (await a.call()).todayMatches;
  assert.equal((await a.join()).me.state, 'waiting');
  const samePerson = await user(ai[0]);
  assert.equal((await samePerson.join()).me.state, 'waiting', 'Same roster member cannot match themselves across browsers');
  await samePerson.call({action:'cancel'});
  assert.equal((await b.join()).me.state, 'waiting', 'Different departments stay separate');
  const joined = await c.join();
  assert.equal(joined.me.state, 'matched'); assert.equal(joined.partner.memberId, a.member.id);
  assert.equal(joined.todayMatches, baseline + 1, 'A pair counts once, not twice');
  assert(joined.me.matched >= joined.me.created);
  const matchedA = await a.call({ action: 'heartbeat' });
  assert.equal(matchedA.partner.memberId, c.member.id);
  assert.equal(matchedA.todayMatches, baseline + 1, 'Heartbeat must not double count');
  assert.equal('owner' in matchedA.me, false); assert.equal('owner' in matchedA.partner, false);
  const duplicate = await a.call({ action: 'join', memberId: full[1].id, team: full[1].team });
  assert.equal(duplicate.me.department, 'AI', 'Duplicate join preserves active ticket');
  assert.equal(duplicate.todayMatches, baseline + 1);
  const going = await a.call({ action: 'meeting', role: 'go' });
  assert.equal(going.me.meetingRole, 'go'); assert.equal(going.partner.meetingRole, 'stay');
  const waiting = await c.call();
  assert.equal(waiting.me.meetingRole, 'stay');
  await Promise.all([a.call({ action: 'meeting', role: 'stay' }), c.call({ action: 'meeting', role: 'stay' })]);
  const simultaneous = await a.call();
  assert.notEqual(simultaneous.me.meetingRole, simultaneous.partner.meetingRole, 'Concurrent choices remain complementary');
  assert.equal((await a.call({action:'meeting',role:'stay',placeId:'invalid'})).status,400);
  assert.equal((await a.call({ action: 'rematch' })).me.state, 'waiting');
  const released = await c.call({ action: 'heartbeat' });
  assert.equal(released.me.state, 'waiting', 'Previous pair excluded');
  assert.equal(released.me.meetingRole, null); assert.equal('meetingPlace' in released, false);
  const d = await user(ai[2]); assert.equal((await d.join()).me.state, 'matched');
  const matchedD = await d.call();
  assert.equal(matchedD.me.meetingRole, null, 'New pair clears earlier meeting decision');
  const peer = users.find(u => u.member.id === matchedD.partner.memberId);
  await d.call({ action: 'complete' });
  assert.equal((await peer.call()).me.state, 'completed', 'Completion reaches both');
  for (const u of users) await u.call({ action: 'cancel' });
  const beforeConcurrent = (await a.call()).todayMatches;
  const concurrent = await Promise.all(ai.slice(3,13).map(m => user(m)));
  await Promise.all(concurrent.map(u => u.join()));
  const states = await Promise.all(concurrent.map(u => u.call()));
  assert(states.every(s => s.me.state === 'matched'), JSON.stringify(states));
  assert.equal(new Set(states.map(s => s.partner.memberId)).size, 10, 'No double assignment');
  assert.equal(states[0].todayMatches, beforeConcurrent + 5, 'Ten people are five matches');
  for (let i=0;i<states.length;i++) { const peerIndex = concurrent.findIndex(u => u.member.id === states[i].partner.memberId); assert.equal(states[peerIndex].partner.memberId, concurrent[i].member.id); }
  const cancelPeer = concurrent.find(u => u.member.id === states[0].partner.memberId);
  await concurrent[0].call({action:'cancel'});
  assert.equal((await cancelPeer.call()).me.state, 'waiting');
  const cloudA = await user(cloud[0]), cloudB = await user(cloud[1]);
  assert.equal((await cloudA.join()).me.state, 'waiting');
  assert.equal((await cloudB.join()).partner.memberId, cloudA.member.id);
  const outsider = await user(full[2]);
  const outside = await outsider.call(); assert.equal(outside.me, null); assert.equal(outside.partner, null); assert.equal('meetingPlace' in outside, false);
  assert.equal((await outsider.call({action:'join',memberId:ai[0].id,team:'20팀'})).status,400);
  assert.equal((await outsider.call({action:'join',memberId:'invalid',team:'14팀'})).status,400);
  assert.equal((await outsider.call({action:'bad'})).status,400);
  const spoof = await outsider.call({action:'join',memberId:full[2].id,team:full[2].team,name:'spoof',department:'AI'});
  assert.equal(spoof.me.name,full[2].name); assert.equal(spoof.me.department,'풀스택','Server owns name and track');
  const noSession = await fetch(`${base}/api/match`, {method:'POST',headers:{origin:new URL(base).origin,'content-type':'application/json'},body:JSON.stringify({action:'join'})}); assert.equal(noSession.status,401);
  const foreign = await fetch(`${base}/api/match`, {method:'POST',headers:{origin:'https://example.org','content-type':'application/json'},body:'{}'}); assert.equal(foreign.status,403);
  console.log('PASS: roster validation, reciprocal D1 matching, ten concurrent clients, daily pair count/idempotency, elapsed timestamps, complementary meeting choices/concurrency, rematch reset, cancellation, completion, privacy, server-derived track, session and origin protections.');
} finally { for (const u of users) await u.call({action:'cancel'}); }
